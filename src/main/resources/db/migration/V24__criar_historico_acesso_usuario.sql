-- Cria a trilha de auditoria dos últimos acessos e eventos de segurança da conta do usuário.

CREATE TABLE IF NOT EXISTS historico_acesso_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id UUID NOT NULL,
    estabelecimento_id UUID NOT NULL,
    tipo_evento VARCHAR(30) NOT NULL,
    ip_origem VARCHAR(45),
    dispositivo VARCHAR(120),
    user_agent VARCHAR(512),
    ocorrido_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_historico_acesso_usuario_tipo
        CHECK (tipo_evento IN ('LOGIN_SUCESSO', 'SENHA_INCORRETA', 'SENHA_ALTERADA')),

    CONSTRAINT fk_historico_acesso_usuario_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuario(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_historico_acesso_usuario_estabelecimento
        FOREIGN KEY (estabelecimento_id)
        REFERENCES estabelecimento(id)
);

CREATE INDEX IF NOT EXISTS idx_historico_acesso_usuario_ocorrido_em
    ON historico_acesso_usuario(usuario_id, ocorrido_em DESC);
