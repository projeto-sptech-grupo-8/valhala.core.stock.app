    ADD COLUMN IF NOT EXISTS tipo VARCHAR(15) NOT NULL DEFAULT 'PADRAO',
    ADD COLUMN IF NOT EXISTS volume_embalagem_ml NUMERIC(12,3);

ALTER TABLE produto
    ALTER COLUMN preco_custo SET DEFAULT 0;

UPDATE produto
SET preco_custo = 0
WHERE preco_custo IS NULL;

ALTER TABLE produto
    ALTER COLUMN preco_custo SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'produto'::regclass AND conname = 'ck_produto_tipo'
    ) THEN
        ALTER TABLE produto ADD CONSTRAINT ck_produto_tipo
            CHECK (tipo IN ('PADRAO', 'DRINK')) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'produto'::regclass AND conname = 'ck_produto_volume_embalagem'
    ) THEN
        ALTER TABLE produto ADD CONSTRAINT ck_produto_volume_embalagem
            CHECK (volume_embalagem_ml IS NULL OR volume_embalagem_ml > 0) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'produto'::regclass AND conname = 'ck_produto_preco_venda_positivo'
    ) THEN
        ALTER TABLE produto ADD CONSTRAINT ck_produto_preco_venda_positivo
            CHECK (preco_venda > 0) NOT VALID;
    END IF;
END $$;

