-- Saldo por lote, com validade, para consumo FEFO (primeiro a vencer, primeiro a sair).
-- A soma dos lotes de um estoque é igual a estoque.quantidade_atual (mesma unidade-base).
CREATE TABLE IF NOT EXISTS lote_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estoque_id INT NOT NULL,
    codigo VARCHAR(100) NOT NULL,
    validade DATE,
    quantidade_atual NUMERIC(12,3) NOT NULL DEFAULT 0,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_lote_estoque_codigo UNIQUE (estoque_id, codigo),
    CONSTRAINT ck_lote_estoque_quantidade CHECK (quantidade_atual >= 0),
    CONSTRAINT fk_lote_estoque_estoque FOREIGN KEY (estoque_id) REFERENCES estoque(id)
);

CREATE INDEX IF NOT EXISTS idx_lote_estoque_validade
    ON lote_estoque(estoque_id, validade);

-- Rastreabilidade: quanto de cada lote cada movimentação criou ou consumiu.
CREATE TABLE IF NOT EXISTS movimentacao_estoque_lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movimentacao_id BIGINT NOT NULL,
    lote_id BIGINT NOT NULL,
    quantidade NUMERIC(12,3) NOT NULL,

    CONSTRAINT ck_movimentacao_lote_quantidade CHECK (quantidade > 0),
    CONSTRAINT fk_movimentacao_lote_movimentacao FOREIGN KEY (movimentacao_id)
        REFERENCES movimentacao_estoque(id),
    CONSTRAINT fk_movimentacao_lote_lote FOREIGN KEY (lote_id)
        REFERENCES lote_estoque(id)
);

CREATE INDEX IF NOT EXISTS idx_movimentacao_lote_movimentacao
    ON movimentacao_estoque_lote(movimentacao_id);

CREATE INDEX IF NOT EXISTS idx_movimentacao_lote_lote
    ON movimentacao_estoque_lote(lote_id);

-- Saldo existente não tem lote/validade conhecidos: vira o lote SEM-LOTE, sem validade.
INSERT INTO lote_estoque (estoque_id, codigo, validade, quantidade_atual)
SELECT e.id, 'SEM-LOTE', NULL, e.quantidade_atual
FROM estoque e
WHERE e.quantidade_atual > 0
  AND NOT EXISTS (SELECT 1 FROM lote_estoque l WHERE l.estoque_id = e.id);
