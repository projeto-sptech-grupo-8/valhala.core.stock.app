    'INT - tabela de domínio interno';

COMMENT ON COLUMN funcionalidade.id IS
    'INT - tabela de domínio interno';

COMMENT ON COLUMN usuario.id IS
    'UUID - entidade principal e segurança do usuário';

COMMENT ON COLUMN preferencia_notificacao.id IS
    'INT - configuração interna do usuário';

COMMENT ON COLUMN categoria.id IS
    'INT - tabela de domínio interno e baixa cardinalidade';

COMMENT ON COLUMN produto.id IS
    'UUID - entidade exposta em APIs e operações comerciais';

COMMENT ON COLUMN estoque.id IS
    'INT - entidade interna vinculada ao produto';

